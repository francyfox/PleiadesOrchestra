import { Database } from "bun:sqlite";
import { drizzle } from "drizzle-orm/bun-sqlite";
import { migrate } from "drizzle-orm/bun-sqlite/migrator";

export const INIT_SQL_HEADER = `-- Generated by \`bun run db:snapshot\` from the drizzle migrations. Do not edit.
-- First-time setup only: services still apply incremental migrations at startup.
-- Contains the full schema, seed data and the __drizzle_migrations rows
-- (so the migrator treats every existing migration as applied).
`;

type MasterRow = { type: string; name: string; tbl_name: string; sql: string };

/** User schema objects (tables, indexes, triggers, views) in creation order — dependency-safe. */
export function schemaObjects(sqlite: Database): MasterRow[] {
	return sqlite
		.query<MasterRow, []>(
			"SELECT type, name, tbl_name, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite\\_%' ESCAPE '\\' AND sql IS NOT NULL ORDER BY rowid",
		)
		.all();
}

/** Deterministic SQL dump (schema, then rows of every table) of a migrated database. */
export function dumpSql(sqlite: Database): string {
	const objects = schemaObjects(sqlite);
	const lines = ["BEGIN;", "PRAGMA defer_foreign_keys = ON;"];
	for (const o of objects) lines.push(`${o.sql};`);
	for (const o of objects.filter((o) => o.type === "table")) {
		const cols = sqlite
			.query<{ name: string }, []>(`PRAGMA table_info("${o.name}")`)
			.all()
			.map((c) => `"${c.name}"`);
		const quoted = cols.map((c) => `quote(${c})`).join(", ");
		const rows = sqlite
			.query<Record<string, string>, []>(
				`SELECT ${quoted} FROM "${o.name}" ORDER BY rowid`,
			)
			.values() as unknown as string[][];
		for (const r of rows) {
			lines.push(
				`INSERT INTO "${o.name}" (${cols.join(", ")}) VALUES (${r.join(", ")});`,
			);
		}
	}
	lines.push("COMMIT;");
	return `${lines.join("\n")}\n`;
}

/** Runs the real migrator over `migrationsDir` in a temp in-memory DB and dumps it. */
export function buildInitSql(migrationsDir: string): string {
	const sqlite = new Database(":memory:");
	try {
		migrate(drizzle(sqlite), { migrationsFolder: migrationsDir });
		return INIT_SQL_HEADER + dumpSql(sqlite);
	} finally {
		sqlite.close();
	}
}
