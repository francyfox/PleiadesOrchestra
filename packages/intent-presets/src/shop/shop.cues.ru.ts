import { STORE_NAMES } from "./shop.cues.en.ts";
import { type LanguageCues, stems } from "./shop.cues.ts";

// Russian words end differently (stems, no end boundary). A Latin shop name inside a Russian sentence
// («давай в Greenleaf») counts as a store word here too.
const STORE_WORD = `${stems("магазин", "маркет")}|(?<![\\p{L}\\p{N}])(?:${STORE_NAMES.join("|")})(?![\\p{L}\\p{N}])`;

export const ru: LanguageCues = {
	language: "ru",
	// People skip the dots: `ё` is `е` in the message, so in the patterns too.
	normalize: (text) => text.replaceAll("ё", "е"),
	normalizePattern: (pattern) => pattern.replaceAll("ё", "е"),
	slots: {
		removeFromCart: [
			stems(
				"удал",
				"убер",
				"убра",
				"выкин",
				"достан",
				"не\\s+надо",
				"не\\s+нужн",
				"не\\s+хочу",
				"очист",
				"опустош",
			),
			stems("передума"),
		],
		checkout: [
			stems(
				"оформ",
				"оплат",
				"оплач",
				"к\\s+оплате",
				"рассчита",
				"заверш\\p{L}*\\s+(?:покупк|заказ)",
			),
			stems("(?:всё|все),?\\s+заказ"),
		],
		chooseStore: [
			`(?=.*(?:${STORE_WORD}))(?=.*(?:${stems("перейд", "переключ", "смени", "давай\\s+в", "покупа\\p{L}*\\s+в", "заказыва\\p{L}*\\s+буду\\s+в", "в\\s+другой")})).*`,
		],
		select: [
			`(?=.*${stems("открой", "расскажи", "покажи")})(?=.*${stems("перв", "втор", "трет", "подробн")}).*`,
		],
		navigate: [
			`(?=.*(?:${stems("открой", "покажи", "перейд", "зайди", "где", "что\\s+(?:у\\s+меня\\s+)?в(?![\\p{L}\\p{N}])")}))(?=.*(?:${stems("корзин", "заказ", "рецепт")})).*`,
		],
		compare: [
			stems("сравн", "разниц", "что\\s+лучше", "как(?:ой|ая|ое)\\s+лучше"),
		],
		paginate: [
			stems(
				"следующ",
				"предыдущ",
				"дальше",
				"покажи\\s+(?:ещё|еще)",
				"ещё\\s+результат",
			),
		],
		search: [
			stems(
				"найд",
				"найти",
				"поищ",
				"ищи",
				"ищу",
				"есть\\s+ли",
				"есть\\s+что",
				"что\\s+(?:у\\s+вас\\s+)?есть",
				"как(?:ие|ой)\\s+у\\s+вас",
				"что\\s+вы\\s+прода",
			),
		],
		buy: [
			stems(
				"купи",
				"куплю",
				"купить",
				"покупа",
				"закаж",
				"добав",
				"полож",
				"закин",
				"бер(?:и|ём|ем)",
			),
		],
		filter: [
			stems(
				"только",
				"дешевле",
				"дешёв",
				"дешев",
				"дороже",
				"без\\s",
				"безглютен",
				"веган",
				"органич",
			),
		],
		wantToBuy: [stems("мне\\s+нуж", "хочу", "надо")],
		chat: [
			`^\\s*(?:${stems("привет", "здравств", "добр(?:ый|ое|ого|ых)", "хай", "спасибо", "благодар", "пока(?![\\p{L}\\p{N}])", "кто\\s+ты", "как\\s+дела", "что\\s+ты\\s+умеешь", "расскажи\\s+о\\s+себе")})`,
			stems("погод"),
		],
	},
	allOfThem: [
		stems("очист", "опустош", "кажд", "целиком", "полностью"),
		// Whole words (`все` must not start «всегда»).
		`(?<![\\p{L}\\p{N}])(?:все|всё|всех|всю)(?![\\p{L}\\p{N}])`,
	],
};
