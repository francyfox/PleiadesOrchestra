import { Glob } from "bun";
import mjml2html from "mjml";

const root = new URL("..", import.meta.url).pathname;

/** Compiles `templates/<kind>.mjml` (not `_*` partials) into the TS source of `src/generated.ts`. */
export async function compileTemplates(): Promise<string> {
	const kinds = [...new Glob("[!_]*.mjml").scanSync(`${root}templates`)]
		.map((file) => file.replace(/\.mjml$/, ""))
		.sort();
	const entries: string[] = [];
	for (const kind of kinds) {
		const path = `${root}templates/${kind}.mjml`;
		const { html, errors } = await mjml2html(await Bun.file(path).text(), {
			filePath: path,
			ignoreIncludes: false,
			validationLevel: "strict",
		});
		if (errors.length) throw new Error(`${kind}: ${JSON.stringify(errors)}`);
		entries.push(`\t${JSON.stringify(kind)}: ${JSON.stringify(html)},`);
	}
	return `// Generated by \`bun run build:templates\` from templates/*.mjml. Do not edit.\nexport const TEMPLATES = {\n${entries.join("\n")}\n} as const;\n`;
}

if (import.meta.main) {
	await Bun.write(`${root}src/generated.ts`, await compileTemplates());
}
